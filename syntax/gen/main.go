// Command gen writes the node kinds, field names and typed views of package
// syntax from tree-sitter's description of the grammar, so the compiler's tree
// can't drift from tree-sitter-eyelang/grammar.js.
//
// Run it with `task generate`, which first runs `tree-sitter generate` to
// produce tree-sitter-eyelang/src/node-types.json.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

type nodeType struct {
	Type     string               `json:"type"`
	Named    bool                 `json:"named"`
	Fields   map[string]childInfo `json:"fields"`
	Children *childInfo           `json:"children"`
	Subtypes []typeRef            `json:"subtypes"`
}

type childInfo struct {
	Multiple bool      `json:"multiple"`
	Required bool      `json:"required"`
	Types    []typeRef `json:"types"`
}

type typeRef struct {
	Type  string `json:"type"`
	Named bool   `json:"named"`
}

// tokens maps named leaves of the grammar to the token kinds of the lexer.
var tokens = map[string]string{
	"identifier":      "Ident",
	"type_identifier": "TypeIdent",
	"integer":         "Int",
	"float":           "Float",
	"date":            "Date",
	"time":            "Time",
	"string_content":  "StringText",
	"escape_sequence": "StringEscape",
	"comment":         "Comment",
	"unit_name":       "UnitName",
}

// renamed holds node names whose Go name would clash with a Field constant.
var renamed = map[string]string{
	"field_pattern": "NamedFieldPattern",
}

func main() {
	in := "../tree-sitter-eyelang/src/node-types.json"
	data, err := os.ReadFile(in)
	if err != nil {
		log.Fatalf("%v (run `tree-sitter generate` in tree-sitter-eyelang first, or `task generate`)", err)
	}
	var types []nodeType
	if err := json.Unmarshal(data, &types); err != nil {
		log.Fatal(err)
	}

	var nodes, supertypes []nodeType
	fieldSet := map[string]bool{}
	for _, t := range types {
		switch {
		case !t.Named:
		case len(t.Subtypes) > 0:
			supertypes = append(supertypes, t)
		case tokens[t.Type] != "":
		default:
			nodes = append(nodes, t)
			for f := range t.Fields {
				fieldSet[f] = true
			}
		}
	}
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].Type < nodes[j].Type })
	fields := make([]string, 0, len(fieldSet))
	for f := range fieldSet {
		fields = append(fields, f)
	}
	sort.Strings(fields)

	write("kind_gen.go", kinds(nodes, fields, supertypes))
	write("view_gen.go", views(nodes))
}

func write(name string, src []byte) {
	out, err := format.Source(src)
	if err != nil {
		log.Fatalf("formatting %s: %v\n%s", name, err, src)
	}
	if err := os.WriteFile(name, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func header(b *bytes.Buffer) {
	b.WriteString("// Code generated by `go run ./gen` from tree-sitter-eyelang/src/node-types.json. DO NOT EDIT.\n\npackage syntax\n\n")
}

func goName(tsName string) string {
	if n, ok := renamed[tsName]; ok {
		return n
	}
	if n, ok := tokens[tsName]; ok {
		return n
	}
	var b strings.Builder
	for _, part := range strings.Split(strings.TrimPrefix(tsName, "_"), "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func kinds(nodes []nodeType, fields []string, supertypes []nodeType) []byte {
	var b bytes.Buffer
	header(&b)

	b.WriteString("// Node kinds, one for each named node of the grammar.\nconst (\n")
	for i, n := range nodes {
		if i == 0 {
			fmt.Fprintf(&b, "\t%s Kind = firstNode + 1 + iota // %s\n", goName(n.Type), n.Type)
		} else {
			fmt.Fprintf(&b, "\t%s // %s\n", goName(n.Type), n.Type)
		}
	}
	b.WriteString(")\n\nvar nodeNames = map[Kind]string{\n\tErrorNode: \"ERROR\",\n")
	for _, n := range nodes {
		fmt.Fprintf(&b, "\t%s: %q,\n", goName(n.Type), n.Type)
	}
	b.WriteString("}\n\n")

	b.WriteString("// Fields, named as in the grammar's field() calls.\nconst (\n\tNoField Field = iota\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\tField%s\n", goName(f))
	}
	b.WriteString(")\n\nvar fieldNames = [...]string{\n\tNoField: \"\",\n")
	for _, f := range fields {
		fmt.Fprintf(&b, "\tField%s: %q,\n", goName(f), f)
	}
	b.WriteString("}\n\n")

	for _, s := range supertypes {
		name := goName(s.Type)
		fmt.Fprintf(&b, "// Is%s reports whether nodes of this kind are %ss (%s in the grammar).\n", name, strings.ToLower(name), s.Type)
		fmt.Fprintf(&b, "func (k Kind) Is%s() bool {\n\tswitch k {\n\tcase ", name)
		var kinds []string
		for _, t := range s.Subtypes {
			kinds = append(kinds, goName(t.Type))
		}
		sort.Strings(kinds)
		b.WriteString(strings.Join(kinds, ", "))
		b.WriteString(":\n\t\treturn true\n\t}\n\treturn false\n}\n\n")
	}
	return b.Bytes()
}

func views(nodes []nodeType) []byte {
	var b bytes.Buffer
	header(&b)
	b.WriteString("// Typed views give later phases named access to a node's parts. Each view\n" +
		"// wraps a node of one kind; its methods return the children with that field.\n\n")
	for _, n := range nodes {
		name := goName(n.Type)
		view := name + "View"
		fmt.Fprintf(&b, "// %s is a typed view of %s node.\ntype %s struct{ Node *Node }\n\n", view, article(n.Type), view)
		fmt.Fprintf(&b, "// As%s returns a view of n if it is %s.\n", name, article(n.Type))
		fmt.Fprintf(&b, "func As%s(n *Node) (%s, bool) {\n\tif n == nil || n.Kind != %s {\n\t\treturn %s{}, false\n\t}\n\treturn %s{n}, true\n}\n\n",
			name, view, name, view, view)

		fieldNames := make([]string, 0, len(n.Fields))
		for f := range n.Fields {
			fieldNames = append(fieldNames, f)
		}
		sort.Strings(fieldNames)
		for _, f := range fieldNames {
			info := n.Fields[f]
			method := goName(f)
			if info.Multiple {
				fmt.Fprintf(&b, "// %s returns the %s children (%s).\nfunc (v %s) %s() []*Node { return v.Node.ChildrenByField(Field%s) }\n\n",
					method, f, typeList(info.Types), view, method, goName(f))
			} else {
				opt := ""
				if !info.Required {
					opt = ", or nil"
				}
				fmt.Fprintf(&b, "// %s returns the %s child (%s)%s.\nfunc (v %s) %s() *Node { return v.Node.ChildByField(Field%s) }\n\n",
					method, f, typeList(info.Types), opt, view, method, goName(f))
			}
		}
		if n.Children != nil {
			fmt.Fprintf(&b, "// Items returns the named children that have no field (%s).\nfunc (v %s) Items() []*Node { return v.Node.unfielded() }\n\n",
				typeList(n.Children.Types), view)
		}
	}
	return b.Bytes()
}

func article(name string) string {
	if strings.ContainsRune("aeiou", rune(name[0])) {
		return "an " + name
	}
	return "a " + name
}

func typeList(refs []typeRef) string {
	var names []string
	for _, r := range refs {
		if r.Named {
			names = append(names, r.Type)
		}
	}
	sort.Strings(names)
	return strings.Join(names, ", ")
}
