// A program that needs the runner is built as B′ (compilation.md, "Where
// the runtime lives"): the Go runner is the binary's main, and the
// program's C, compiled by zig into a static library, is linked into it
// through cgo, by the Go toolchain internal/gotool pins, with zig as the C
// compiler. Linux binaries are static, linked against musl.
//
// The runner's Go source travels inside eye: it is embedded here, and
// written into the module the build makes, as the module eyelang, which the
// program's main package requires and replaces with that copy. Nothing is
// fetched but Go and zig, and nothing is read from the network or GOPATH
// during the build. Today the runner is the package hosted, which only runs
// the program's main or tests; when 7.6 hosts entities and jobs, the
// runner's packages and their dependencies, vendored, are embedded the same
// way, and the build uses -mod=vendor.

//go:embed hosted/*.go
var hostedFS embed.FS

// runnerTargets are the targets the runner is built for, and whether each
// one's binary is linked statically. macOS has no static binaries: one
// links libSystem, as every Mac program does.
var runnerTargets = map[string]struct{ static bool }{
	"linux/amd64":  {static: true},
	"linux/arm64":  {static: true},
	"darwin/amd64": {},
	"darwin/arm64": {},
}

// libresolv is a link-time stub of macOS's resolver library, which Go's
// runtime imports on macOS (internal/syscall/unix) and every Mac has, but
// zig's macOS SDK doesn't describe. It names the functions Go calls.
const libresolv = `--- !tapi-tbd
tbd-version:     4
targets:         [ x86_64-macos, arm64-macos ]
install-name:    '/usr/lib/libresolv.9.dylib'
exports:
  - targets:         [ x86_64-macos, arm64-macos ]
    symbols:         [ _res_9_nclose, _res_9_ninit, _res_9_nsearch ]
...
`

// buildRunner links the program's C files into the runner, writing the
// binary to opts.Out.
func buildRunner(files []File, opts BuildOptions) error {
	target := opts.Target
	if target == "" {
		target = HostTarget()
	}
	if _, ok := runnerTargets[target]; !ok {
		var names []string
		for n := range runnerTargets {
			names = append(names, n)
		}
		sort.Strings(names)
		return fmt.Errorf("eye build --runner doesn't build for %q yet: it builds for %s", target, strings.Join(names, ", "))
	}
	work, err := os.MkdirTemp("", "eye-runner-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(work)

	// The program's module: its main runs the runner.
	mod := map[string]string{
		"go.mod":         "module eyeprogram\n\ngo " + gotool.Version + "\n\nrequire eyelang v0.0.0\n\nreplace eyelang => ./eyelang\n",
		"main.go":        "// Code generated by eye build --runner. DO NOT EDIT.\n\npackage main\n\nimport \"eyelang/cgen/hosted\"\n\nfunc main() { hosted.Exit(hosted.Main()) }\n",
		"eyelang/go.mod": "module eyelang\n\ngo " + gotool.Version + "\n",
	}
	src, _ := fs.Glob(hostedFS, "hosted/*.go")
	for _, name := range src {
		data, _ := hostedFS.ReadFile(name)
		mod["eyelang/cgen/"+name] = string(data)
	}
	if err := writeTree(work, mod); err != nil {
		return err
	}
	// The program's C, as a static library the runner links.
	lib := opts
	lib.Target, lib.Archive, lib.Runner = target, true, false
	lib.Out = filepath.Join(work, "libeyeprogram.a")
	if err := Compile(files, lib); err != nil {
		return err
	}
	return goLink(work, opts.Out, target, "eyehosted", []string{lib.Out, "-lm"}, nil, opts.Progress)
}

// writeTree writes files, by their paths below dir.
func writeTree(dir string, files map[string]string) error {
	for name, text := range files {
		p := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(p, []byte(text), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// goLink builds the Go module in dir into the binary out for target, with
// cgo, zig as the C compiler and the pinned Go: the step every runner build
// ends with. ldflags go to zig as it links, the program's archive among
// them, and env is added to the build's environment.
func goLink(dir, out, target, tags string, ldflags, env []string, progress io.Writer) error {
	rt := runnerTargets[target]
	goExe, err := gotool.Path(progress)
	if err != nil {
		return err
	}
	zigExe, err := zig.Path(progress)
	if err != nil {
		return err
	}
	goos, goarch, _ := strings.Cut(target, "/")
	link := "-s -w -linkmode external"
	if rt.static {
		link += " -extldflags -static"
	}
	if goos == "darwin" {
		sdk := filepath.Join(dir, "sdk")
		if err := os.MkdirAll(sdk, 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(sdk, "libresolv.tbd"), []byte(libresolv), 0o644); err != nil {
			return err
		}
		ldflags = append(ldflags, "-L"+sdk)
	}
	abs, err := filepath.Abs(out)
	if err != nil {
		return err
	}
	cmd := exec.Command(goExe, "build", "-trimpath", "-tags", tags, "-ldflags", link, "-o", abs, ".")
	cmd.Dir = dir
	root, _ := gotool.Root(nil)
	cmd.Env = append(os.Environ(),
		"GOROOT="+root,
		"GOOS="+goos,
		"GOARCH="+goarch,
		"CGO_ENABLED=1",
		"CC="+zigExe+" cc -target "+Targets[target],
		"CGO_LDFLAGS="+strings.Join(ldflags, " "),
		// Only what the module holds: no toolchain switch, no proxy, no
		// workspace, and none of the user's go env settings.
		"GOTOOLCHAIN=local",
		"GOPROXY=off",
		"GOFLAGS=-mod=mod",
		"GOWORK=off",
		"GOENV=off",
	)
	cmd.Env = append(cmd.Env, env...)
	if outb, err := cmd.CombinedOutput(); err != nil {
		return fmt.Errorf("linking %s into the runner: %v\n%s", out, err, outb)
	}
	return nil
}
