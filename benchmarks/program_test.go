package benchmarks

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"testing"
)

// funcsPerModule is how many generated functions each module holds: about
// 1,100 lines, near the size of the largest real modules (digest, core).
const funcsPerModule = 30

// program writes one program of at least lines lines into dir: modules
// m0000, m0001, … of ordinary core-language code (records, variants,
// matches, lists, loops, interpolated strings), and a main that calls each
// module's run, so every function is reachable and a build compiles all of
// it. Unlike corpus, it is one program, and it only uses what the C back
// end compiles. It returns the number of modules and lines written.
func program(tb testing.TB, dir string, lines int) (modules, total int) {
	tb.Helper()
	var main bytes.Buffer
	var calls bytes.Buffer
	for total < lines {
		name := fmt.Sprintf("m%04d", modules)
		src := module(modules)
		path := filepath.Join(dir, name, name+".eye")
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			tb.Fatal(err)
		}
		if err := os.WriteFile(path, src, 0o644); err != nil {
			tb.Fatal(err)
		}
		total += bytes.Count(src, []byte("\n"))
		fmt.Fprintf(&main, "import %s\n", name)
		fmt.Fprintf(&calls, "  total += %s.run(3)\n", name)
		modules++
	}
	fmt.Fprintf(&main, "\npub fn main(args: List(String)) uses {stdio} {\n  var total = 0\n%s  print(\"{total}\")\n}\n", calls.Bytes())
	total += bytes.Count(main.Bytes(), []byte("\n"))
	if err := os.WriteFile(filepath.Join(dir, "main.eye"), main.Bytes(), 0o644); err != nil {
		tb.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "eye.toml"), nil, 0o644); err != nil {
		tb.Fatal(err)
	}
	return modules, total
}

// module is the source of generated module m.
func module(m int) []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by benchmarks/program_test.go: module %d of a program\n# made to measure eye check and eye build.\n", m)
	for i := range funcsPerModule {
		fmt.Fprintf(&b, `
type Shape%[1]d = Circle%[1]d(Int) | Rect%[1]d(Int, Int) | Empty%[1]d

type Item%[1]d = { id: Int, name: String, tags: List(String) }

fn area%[1]d(s: Shape%[1]d) -> Int = match s {
  Circle%[1]d(r) => 3 * r * r
  Rect%[1]d(w, h) => w * h
  Empty%[1]d => 0
}

fn items%[1]d(n: Int) -> List(Item%[1]d) {
  var xs: List(Item%[1]d) = []
  for k in 0..n {
    xs = xs.add({ id: k, name: "item {k} of %[2]d", tags: ["a", "b"] })
  }
  xs
}

fn score%[1]d(n: Int) -> Int {
  var total = 0
  for it in items%[1]d(n) {
    total += it.id * %[3]d
  }
  for s in [Circle%[1]d(n), Rect%[1]d(n, %[1]d), Empty%[1]d] {
    total += area%[1]d(s)
  }
  match total %% 3 {
    0 => total / 3
    1 => total + %[1]d
    _ => total - 1
  }
}
`, i, m, i%7+1)
	}
	b.WriteString("\npub fn run(n: Int) -> Int {\n  var total = 0\n")
	for i := range funcsPerModule {
		fmt.Fprintf(&b, "  total += score%d(n)\n", i)
	}
	b.WriteString("  total\n}\n")
	return b.Bytes()
}
