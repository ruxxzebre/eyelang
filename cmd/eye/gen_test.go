package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestGenPolicy runs eye gen policy on the lab, on a program with an error,
// and with a wrong target or namespace. internal/netpolicy's golden tests
// check what the policies say.
func TestGenPolicy(t *testing.T) {
	bad := t.TempDir()
	files := map[string]string{
		"notify/notify.eye": "@port(3001)\n@allow(digest)\ncontract Notify {\n  query ping() -> Int\n}\n",
		"digest/digest.eye": "fn nothing() = 1\n",
		"trains/trains.eye": "import notify\nfn ping() = notify.ping()\n",
		"main.eye":          "import trains\nimport digest\n",
	}
	for name, src := range files {
		path := filepath.Join(bad, name)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	cases := []struct {
		name   string
		args   []string
		code   int
		stdout []string // each must appear; nil means stdout is empty
		stderr string
	}{
		{"the lab", []string{"gen", "policy", "--namespace", "homelab", "../../testdata/lab"}, 0, []string{
			"# Generated by eye gen policy from ../../testdata/lab.",
			"kind: NetworkPolicy\nmetadata:\n  name: lab-notify\n  namespace: homelab\n",
			"      eyelang.module: notifier\n",
			"          port: 3001\n",
		}, ""},
		{"a program with errors writes nothing", []string{"gen", "policy", bad}, exitErrors, nil, "module trains may not call ping, an operation of Notify"},
		{"a namespace Kubernetes refuses", []string{"gen", "policy", "--namespace", "Home_Lab", "../../testdata/lab"}, exitUsage, nil, `the namespace "Home_Lab" isn't a Kubernetes namespace name`},
		{"a file instead of a directory", []string{"gen", "policy", "../../testdata/lab/lab.eye"}, exitUsage, nil, "lab.eye is a file; give the program's directory"},
		{"no target", []string{"gen"}, exitUsage, nil, "usage: eye gen <target>"},
		{"an unknown target", []string{"gen", "helm"}, exitUsage, nil, `eye gen: unknown target "helm"`},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			if code := run(c.args, &stdout, &stderr); code != c.code {
				t.Errorf("exit code %d, want %d; stderr:\n%s", code, c.code, stderr.String())
			}
			if c.stdout == nil && stdout.Len() > 0 {
				t.Errorf("want nothing on stdout, got:\n%s", stdout.String())
			}
			for _, want := range c.stdout {
				if !strings.Contains(stdout.String(), want) {
					t.Errorf("stdout lacks %q:\n%s", want, stdout.String())
				}
			}
			if !strings.Contains(stderr.String(), c.stderr) {
				t.Errorf("stderr lacks %q:\n%s", c.stderr, stderr.String())
			}
		})
	}
}
