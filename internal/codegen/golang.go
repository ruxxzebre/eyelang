// Go writes the Go package for one module's contracts: its types, with the
// JSON methods that give them the one shape; a client for each contract;
// and a service interface with an http.Handler that serves it.
func Go(prog *ir.Program, mod *ir.Module, opts Options) ([]byte, error) {
	u, err := build(prog, mod)
	if err != nil {
		return nil, err
	}
	g := &goGen{unit: u}
	g.goNames()
	pkg := opts.Package
	if pkg == "" {
		pkg = goPackageName(mod.Name)
	}
	g.header(opts.Source, pkg)
	for _, n := range u.types {
		g.namedType(n)
	}
	for _, c := range u.contracts {
		g.client(c)
		g.service(c)
	}
	g.raw(goHelpers)
	if len(u.errs) > 0 {
		return nil, fmt.Errorf("%s", strings.Join(u.errs, "\n"))
	}
	src, err := format.Source(g.b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("the generated Go doesn't parse, which is a bug in eye gen: %v\n%s", err, g.b.String())
	}
	return src, nil
}

// goPackageName makes a module's name a Go package name.
func goPackageName(name string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(name) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		}
	}
	if b.Len() == 0 {
		return "contract"
	}
	return b.String()
}

type goGen struct {
	*unit
	b bytes.Buffer
}

// goNames spells the names the model gave in Go's way, with initialisms in
// capitals: MessageId is MessageID.
func (g *goGen) goNames() {
	seen := map[string]bool{}
	rename := func(s *string) {
		*s = goName(*s)
		if seen[*s] {
			g.errorf("two declarations would both be named %s in the generated Go", *s)
		}
		seen[*s] = true
	}
	for _, n := range g.types {
		rename(&n.name)
		for _, v := range n.variants {
			if n.single() {
				v.name = n.name
			} else {
				rename(&v.name)
			}
		}
	}
	for _, c := range g.contracts {
		rename(&c.client)
		rename(&c.service)
		for _, o := range c.ops {
			if o.args != "" {
				rename(&o.args)
			}
		}
	}
}

func (g *goGen) p(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

func (g *goGen) raw(s string) { g.b.WriteString(s) }

func (g *goGen) doc(indent, doc string) {
	for _, line := range docLines(doc) {
		if line == "" {
			g.p("%s//", indent)
		} else {
			g.p("%s// %s", indent, line)
		}
	}
}

// comment writes paragraphs of the generator's own prose as a comment.
func (g *goGen) comment(indent string, paragraphs ...string) {
	for _, line := range wrap(paragraphs...) {
		if line == "" {
			g.p("%s//", indent)
		} else {
			g.p("%s// %s", indent, line)
		}
	}
}

func (g *goGen) header(source, pkg string) {
	from := ""
	if source != "" {
		from = " from " + source
	}
	g.p("// Code generated by eye gen go%s; DO NOT EDIT.", from)
	g.p("")
	var names []string
	for _, c := range g.contracts {
		names = append(names, c.ct.Name)
	}
	what := "contract " + names[0]
	if len(names) > 1 {
		what = "contracts " + joinWords(names)
	}
	g.comment("", fmt.Sprintf("Package %s holds the types of %s, a client that calls it over HTTP and a server stub to implement it, from Eyelang module %s. Values go over the wire in Eyelang's one JSON shape (SPECS.md §17).", pkg, what, g.mod.Path))
	g.p("package %s", pkg)
	g.p("")
	g.p("import (")
	for _, imp := range []string{"bytes", "context", "crypto/subtle", "encoding/json", "errors", "fmt", "io", "net", "net/http", "net/url", "reflect", "strconv", "strings", "time"} {
		g.p("\t%q", imp)
	}
	g.p(")")
	g.p("")
}

