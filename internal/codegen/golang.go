// typ is t's Go type.
func (g *goGen) typ(t *ir.TypeExpr) string {
	t = resolve(t)
	if inner := g.optionOf(t); inner != nil {
		if g.isInterface(inner) {
			return g.typ(inner)
		}
		return "*" + g.typ(inner)
	}
	if t.Decl != nil {
		if n := g.named(t); n != nil {
			return n.name
		}
		return "any"
	}
	switch t.Name {
	case "String", "Key", "Zone", "Date", "Time":
		return "string"
	case "Int", "Size":
		return "int64"
	case "Float":
		return "float64"
	case "Bool":
		return "bool"
	case "Duration", "Version", "Approval":
		return t.Name
	case "Instant":
		return "time.Time"
	case "()":
		return "struct{}"
	case "List", "Set":
		if len(t.Args) == 1 {
			return "[]" + g.typ(t.Args[0])
		}
	case "Map":
		if len(t.Args) == 2 {
			return "map[" + g.typ(t.Args[0]) + "]" + g.typ(t.Args[1])
		}
	}
	return "any"
}

// isInterface reports whether t's Go type is an interface: a variant type
// tagged with "kind", or a newtype of one.
func (g *goGen) isInterface(t *ir.TypeExpr) bool {
	n := g.named(t)
	switch {
	case n == nil:
		return false
	case n.kind == kUnion:
		return !n.single()
	case n.kind == kNewtype:
		return g.isInterface(n.inner)
	}
	return false
}

// needsDecode reports whether encoding/json can't read t by itself: it
// holds an interface outside a declared type, which decodes its own fields.
func (g *goGen) needsDecode(t *ir.TypeExpr) bool {
	t = resolve(t)
	if g.isInterface(t) {
		return true
	}
	if inner := g.optionOf(t); inner != nil {
		return g.needsDecode(inner)
	}
	if n := g.named(t); n != nil {
		return n.kind == kNewtype && g.aliased(n) && g.needsDecode(n.inner)
	}
	for _, a := range t.Args {
		if g.needsDecode(a) {
			return true
		}
	}
	return false
}

// dec is a Go expression of type func(json.RawMessage) (T, error) that
// reads t.
func (g *goGen) dec(t *ir.TypeExpr) string {
	t = resolve(t)
	if !g.needsDecode(t) {
		return "plain[" + g.typ(t) + "]"
	}
	if inner := g.optionOf(t); inner != nil {
		if g.isInterface(inner) {
			return "nullable(" + g.dec(inner) + ")"
		}
		return "optional(" + g.dec(inner) + ")"
	}
	if n := g.named(t); n != nil {
		if n.kind == kNewtype {
			return g.dec(n.inner)
		}
		return "decode" + n.name
	}
	switch t.Name {
	case "List", "Set":
		return "listOf(" + g.dec(t.Args[0]) + ")"
	case "Map":
		return "mapOf[" + g.typ(t.Args[0]) + "](" + g.dec(t.Args[1]) + ")"
	}
	return "plain[" + g.typ(t) + "]"
}

// aliased reports whether a newtype is written as an alias of its value's
// type, which keeps that type's methods: anything but a plain value.
func (g *goGen) aliased(n *named) bool {
	t := resolve(n.inner)
	if t.Decl != nil || g.optionOf(t) != nil {
		return true
	}
	switch t.Name {
	case "String", "Key", "Zone", "Date", "Time", "Int", "Size", "Float", "Bool":
		return false
	}
	return true
}

// emptyable reports whether t's Go type is a slice or a map, which
// encoding/json writes as null when it is nil.
func (g *goGen) emptyable(t *ir.TypeExpr) bool {
	s := g.typ(t)
	return strings.HasPrefix(s, "[]") || strings.HasPrefix(s, "map[")
}

func (g *goGen) namedType(n *named) {
	switch n.kind {
	case kRecord:
		g.doc("", n.doc)
		if n.doc == "" {
			g.p("// %s is a record of Eyelang module %s.", n.name, n.decl.Module.Path)
		}
		g.p("type %s struct {", n.name)
		g.structFields(n.fields)
		g.p("}")
		g.p("")
		g.methods(n.name, "", n.fields)
	case kNewtype:
		g.doc("", n.doc)
		if n.doc == "" {
			g.p("// %s wraps one value, which is what goes over the wire.", n.name)
		}
		if g.aliased(n) {
			g.p("type %s = %s", n.name, g.typ(n.inner))
		} else {
			g.p("type %s %s", n.name, g.typ(n.inner))
		}
		g.p("")
	case kEnum:
		g.doc("", n.doc)
		if n.doc == "" {
			g.p("// %s is one of its constants, which go over the wire as strings.", n.name)
		}
		g.p("type %s string", n.name)
		g.p("")
		g.p("// The values of %s.", n.name)
		g.p("const (")
		for _, v := range n.variants {
			g.doc("\t", v.doc)
			g.p("\t%s %s = %q", v.name, n.name, v.value)
		}
		g.p(")")
		g.p("")
		var names, quoted []string
		for _, v := range n.variants {
			names = append(names, v.name)
			quoted = append(quoted, strconv.Quote(v.value))
		}
		g.p("// UnmarshalJSON reads one of %s's values, and nothing else.", n.name)
		g.p("func (x *%s) UnmarshalJSON(data []byte) error {", n.name)
		g.p("\tvar s %s", n.name)
		g.p("\tif json.Unmarshal(data, (*string)(&s)) == nil {")
		g.p("\t\tswitch s {")
		g.p("\t\tcase %s:", strings.Join(names, ", "))
		g.p("\t\t\t*x = s")
		g.p("\t\t\treturn nil")
		g.p("\t\t}")
		g.p("\t}")
		g.p("\treturn fmt.Errorf(%s, describe(data))", strconv.Quote("expected one of "+strings.Join(quoted, ", ")+", found %s"))
		g.p("}")
		g.p("")
	case kUnion:
		if n.single() {
			v := n.variants[0]
			doc := v.doc
			if doc == "" {
				doc = n.doc
			}
			g.doc("", doc)
			if doc != "" {
				g.p("//")
			}
			g.comment("", fmt.Sprintf("%s goes over the wire as an object tagged with its kind.", n.name))
			g.p("type %s struct {", n.name)
			g.structFields(v.fields)
			g.p("}")
			g.p("")
			g.methods(n.name, v.tag, v.fields)
			return
		}
		g.doc("", n.doc)
		if n.doc != "" {
			g.p("//")
		}
		var names []string
		for _, v := range n.variants {
			names = append(names, v.name)
		}
		g.comment("", fmt.Sprintf("%s is one of %s. Each goes over the wire as an object tagged with its kind.", n.name, joinWords(names)))
		g.p("type %s interface {", n.name)
		g.p("\tis%s()", n.name)
		g.p("}")
		g.p("")
		for _, v := range n.variants {
			g.doc("", v.doc)
			if v.doc == "" {
				g.p("// %s is a variant of %s.", v.name, n.name)
			}
			if len(v.fields) == 0 {
				g.p("type %s struct{}", v.name)
			} else {
				g.p("type %s struct {", v.name)
				g.structFields(v.fields)
				g.p("}")
			}
			g.p("")
			g.p("func (%s) is%s() {}", v.name, n.name)
			g.p("")
			g.methods(v.name, v.tag, v.fields)
		}
		g.p("func decode%s(data json.RawMessage) (%s, error) {", n.name, n.name)
		g.p("\tkind, err := kindOf(data)")
		g.p("\tif err != nil {")
		g.p("\t\treturn nil, err")
		g.p("\t}")
		g.p("\tswitch kind {")
		for _, v := range n.variants {
			g.p("\tcase %q:", v.tag)
			g.p("\t\tvar v %s", v.name)
			g.p("\t\tif err := json.Unmarshal(data, &v); err != nil {")
			g.p("\t\t\treturn nil, err")
			g.p("\t\t}")
			g.p("\t\treturn v, nil")
		}
		g.p("\t}")
		g.p("\treturn nil, fmt.Errorf(\"%s has no kind %%q\", kind)", n.name)
		g.p("}")
		g.p("")
	}
}

func (g *goGen) structFields(fields []field) {
	for _, f := range fields {
		g.doc("\t", f.doc)
		g.p("\t%s %s `json:%q`", goName(f.name), g.typ(f.t), f.wire)
	}
}

// methods writes a struct's MarshalJSON, when it is a tagged variant or has
// slices or maps that must not go as null, and its UnmarshalJSON, when a
// field needs decoding.
func (g *goGen) methods(name, tag string, fields []field) {
	var empties []field
	for _, f := range fields {
		if g.emptyable(f.t) {
			empties = append(empties, f)
		}
	}
	if tag != "" || len(empties) > 0 {
		if tag != "" {
			g.p("// MarshalJSON writes %s tagged with its kind.", name)
		} else {
			g.p("// MarshalJSON writes %s with its nil slices and maps as empty ones.", name)
		}
		g.p("func (x %s) MarshalJSON() ([]byte, error) {", name)
		g.p("\ttype fields %s", name)
		g.p("\tf := fields(x)")
		for _, f := range empties {
			g.p("\tif f.%s == nil {", goName(f.name))
			g.p("\t\tf.%s = %s{}", goName(f.name), g.typ(f.t))
			g.p("\t}")
		}
		if tag != "" {
			g.p("\treturn tagged(%q, f)", tag)
		} else {
			g.p("\treturn json.Marshal(f)")
		}
		g.p("}")
		g.p("")
	}
	var decoded []field
	for _, f := range fields {
		if g.needsDecode(f.t) {
			decoded = append(decoded, f)
		}
	}
	if len(decoded) == 0 {
		return
	}
	g.p("// UnmarshalJSON reads %s, with the fields encoding/json can't read alone.", name)
	g.p("func (x *%s) UnmarshalJSON(data []byte) error {", name)
	g.p("\tvar raw struct {")
	for _, f := range fields {
		t := g.typ(f.t)
		if g.needsDecode(f.t) {
			t = "json.RawMessage"
		}
		g.p("\t\t%s %s `json:%q`", goName(f.name), t, f.wire)
	}
	g.p("\t}")
	g.p("\tif err := json.Unmarshal(data, &raw); err != nil {")
	g.p("\t\treturn err")
	g.p("\t}")
	for _, f := range fields {
		if !g.needsDecode(f.t) {
			g.p("\tx.%s = raw.%s", goName(f.name), goName(f.name))
		}
	}
	g.p("\tvar err error")
	for _, f := range decoded {
		g.p("\tif x.%s, err = %s(raw.%s); err != nil {", goName(f.name), g.dec(f.t), goName(f.name))
		g.p("\t\treturn fmt.Errorf(\"%s: %%w\", err)", f.wire)
		g.p("\t}")
	}
	g.p("\treturn nil")
	g.p("}")
	g.p("")
}

// ---------------------------------------------------------------- client

// fieldType is the Go type of an argument's field: a pointer, or an
// interface, when the call may leave it out.
func (g *goGen) fieldType(pp *param) string {
	if !pp.optional || g.isInterface(pp.t) {
		return g.typ(pp.t)
	}
	return "*" + g.typ(pp.t)
}

// signature is an operation's method signature, without its name.
func (g *goGen) signature(o *operation) string {
	var in []string
	in = append(in, "ctx context.Context")
	if o.args != "" {
		in = append(in, "args "+o.args)
	}
	if o.op.Key {
		in = append(in, "key string")
	}
	return "(" + strings.Join(in, ", ") + ") (" + g.typ(o.result) + ", error)"
}

func (g *goGen) opName(c *contract, o *operation) string {
	return c.ct.Module.Name + "." + o.op.Name
}

func (g *goGen) client(c *contract) {
	ct := c.ct
	g.p("// ---------------------------------------------------------------- %s", ct.Name)
	g.p("")
	for _, o := range c.ops {
		if o.args == "" {
			continue
		}
		g.p("// %s are the arguments of %s.%s.", o.args, ct.Name, o.op.Name)
		g.p("type %s struct {", o.args)
		for _, pp := range o.params {
			switch {
			case pp.def != nil:
				g.p("\t// %s is %s when it is nil.", goName(pp.p.Name), strings.ReplaceAll(string(pp.def), "\n", " "))
			case pp.option:
				g.p("\t// %s is left out when it is nil.", goName(pp.p.Name))
			}
			g.p("\t%s %s", goName(pp.p.Name), g.fieldType(pp))
		}
		g.p("}")
		g.p("")
	}
	g.doc("", ct.Doc)
	if ct.Doc != "" {
		g.p("//")
	}
	g.comment("", fmt.Sprintf("%s calls %s's operations over HTTP. A command whose reply was lost returns an *Uncertain error; a request that never reached the service returns the error that stopped it, and can be sent again.", c.client, ct.Name))
	g.p("type %s struct {", c.client)
	g.p("\t// BaseURL is where the service answers, such as http://%s:%d.", ct.Module.Name, max(ct.Port, 80))
	g.p("\tBaseURL string")
	if ct.HTTP.AuthSecret != "" {
		how := "<Secret>"
		if ct.HTTP.AuthBearer {
			how = "Bearer <Secret>"
		}
		g.comment("\t", fmt.Sprintf("Secret is the secret %s, which every request carries in its %s header as %s.", ct.HTTP.AuthSecret, ct.HTTP.AuthHeader, how))
		g.p("\tSecret string")
	}
	g.p("\t// HTTPClient makes the requests; http.DefaultClient when nil.")
	g.p("\tHTTPClient *http.Client")
	g.p("}")
	g.p("")
	g.p("func (c *%s) transport() transport {", c.client)
	switch {
	case ct.HTTP.AuthSecret == "":
		g.p("\treturn transport{baseURL: c.BaseURL, client: c.HTTPClient}")
	case ct.HTTP.AuthBearer:
		g.p("\treturn transport{baseURL: c.BaseURL, client: c.HTTPClient, authHeader: %q, authValue: \"Bearer \" + c.Secret}", ct.HTTP.AuthHeader)
	default:
		g.p("\treturn transport{baseURL: c.BaseURL, client: c.HTTPClient, authHeader: %q, authValue: c.Secret}", ct.HTTP.AuthHeader)
	}
	g.p("}")
	g.p("")
	for _, o := range c.ops {
		g.clientOp(c, o)
	}
}

func (g *goGen) clientOp(c *contract, o *operation) {
	op := o.op
	name := g.opName(c, o)
	if op.Doc != "" {
		g.doc("", op.Doc)
		g.p("//")
		g.p("// It is %s %s.", op.HTTP.Method, op.HTTP.Path)
	} else {
		g.p("// %s is %s %s.", goName(op.Name), op.HTTP.Method, op.HTTP.Path)
	}
	g.p("func (c *%s) %s%s {", c.client, goName(op.Name), g.signature(o))
	g.p("\tvar zero %s", g.typ(o.result))
	g.p("\tr := newCall(%q, %q, %q)", name, op.HTTP.Method, op.HTTP.Path)
	for _, pp := range o.params {
		field := "args." + goName(pp.p.Name)
		put := func(indent, v string) {
			g.p("%sif err := r.put(%q, %q, %s); err != nil {", indent, pp.in, pp.wire, v)
			g.p("%s\treturn zero, err", indent)
			g.p("%s}", indent)
		}
		switch {
		case !pp.optional:
			put("\t", field)
		default:
			v := "*" + field
			if g.isInterface(pp.t) {
				v = field
			}
			g.p("\tif %s != nil {", field)
			put("\t\t", v)
			if pp.def != nil {
				g.p("\t} else {")
				g.p("\t\tr.putJSON(%q, %q, json.RawMessage(%s))", pp.in, pp.wire, strconv.Quote(string(pp.def)))
			}
			g.p("\t}")
		}
	}
	if op.Key {
		g.p("\tr.header.Set(%q, key)", wire.KeyHeader(op))
		if op.KeyField != "" {
			g.p("\tif err := r.put(\"body\", %q, key); err != nil {", op.KeyField)
			g.p("\t\treturn zero, err")
			g.p("\t}")
		}
	}
	key := `""`
	if op.Key {
		key = "key"
	}
	g.p("\tstatus, reply, err := c.transport().send(ctx, r)")
	g.p("\tif err != nil {")
	if op.Command {
		g.p("\t\tif !notSent(err) {")
		g.p("\t\t\treturn zero, &Uncertain{Op: %q, Key: %s}", name, key)
		g.p("\t\t}")
	}
	g.p("\t\treturn zero, err")
	g.p("\t}")
	mapped := map[int]bool{}
	if len(o.statuses) > 0 {
		g.p("\tswitch status {")
		// codes that map to one variant share a case
		var order []string
		cases := map[string][]string{}
		for _, s := range o.statuses {
			mapped[s.code] = true
			if _, ok := cases[s.variant]; !ok {
				order = append(order, s.variant)
			}
			cases[s.variant] = append(cases[s.variant], strconv.Itoa(s.code))
		}
		for _, variant := range order {
			g.p("\tcase %s:", strings.Join(cases[variant], ", "))
			g.statusCase(o, variant)
		}
		g.p("\t}")
	}
	if op.Fresh {
		if !mapped[wire.StaleStatus] {
			g.p("\tif status == %d {", wire.StaleStatus)
			g.p("\t\treturn zero, ErrStale")
			g.p("\t}")
		}
		if !mapped[wire.ExpiredStatus] {
			g.p("\tif status == %d {", wire.ExpiredStatus)
			g.p("\t\treturn zero, ErrExpired")
			g.p("\t}")
		}
	}
	g.p("\tif status >= 200 && status < 300 {")
	if op.Fresh {
		g.p("\t\tif err := freshOutcome(reply, %q, %q); err != nil {", wire.Name("Stale", g.snake), wire.Name("Expired", g.snake))
		g.p("\t\t\treturn zero, err")
		g.p("\t\t}")
	}
	g.p("\t\tv, err := %s(reply)", g.dec(o.result))
	g.p("\t\tif err != nil {")
	g.p("\t\t\treturn zero, r.badReply(status, %q, err)", typeString(o.result))
	g.p("\t\t}")
	g.p("\t\treturn v, nil")
	g.p("\t}")
	if op.Command && !o.httpErr {
		g.p("\tif status >= 500 {")
		g.p("\t\treturn zero, &Uncertain{Op: %q, Key: %s}", name, key)
		g.p("\t}")
	}
	g.p("\treturn zero, &HTTPError{Op: %q, Status: status, Body: string(reply)}", name)
	g.p("}")
	g.p("")
}

// statusCase reads a reply whose status `status:` maps to a variant: the
// body holds the variant's fields.
func (g *goGen) statusCase(o *operation, name string) {
	switch name {
	case "Stale":
		if o.op.Fresh {
			g.p("\t\treturn zero, ErrStale")
			return
		}
	case "Expired":
		if o.op.Fresh {
			g.p("\t\treturn zero, ErrExpired")
			return
		}
	}
	n := g.named(o.result)
	var v *variant
	if n != nil {
		for _, x := range n.variants {
			if x.tag == name {
				v = x
			}
		}
	}
	if v == nil {
		g.errorf("%s.%s: status: maps a reply to %s, which isn't a variant of %s", o.op.Contract.Name, o.op.Name, name, typeString(o.result))
		g.p("\t\treturn zero, nil")
		return
	}
	if n.kind == kEnum {
		g.p("\t\treturn %s, nil", v.name)
		return
	}
	g.p("\t\tv, err := fieldsOf[%s](reply)", v.name)
	g.p("\t\tif err != nil {")
	g.p("\t\t\treturn zero, r.badReply(status, %q, err)", name)
	g.p("\t\t}")
	g.p("\t\treturn v, nil")
}

// ---------------------------------------------------------------- server

func (g *goGen) service(c *contract) {
	ct := c.ct
	paras := []string{fmt.Sprintf("%s is %s's operations that go over HTTP, for a server to implement; New%sHandler serves one. A %s is one too, so a server can pass calls on.", c.service, ct.Name, ct.Name, c.client)}
	if s := internalOps(c); s != "" {
		paras = append(paras, "", s)
	}
	g.comment("", paras...)
	g.p("type %s interface {", c.service)
	for i, o := range c.ops {
		if i > 0 {
			g.p("")
		}
		g.doc("\t", o.op.Doc)
		g.p("\t%s%s", goName(o.op.Name), g.signature(o))
	}
	g.p("}")
	g.p("")
	g.p("var _ %s = (*%s)(nil)", c.service, c.client)
	g.p("")
	served := contractName(ct)
	paras = []string{fmt.Sprintf("New%sHandler serves s over HTTP the way eye run serves %s: each operation at its @http method and path, its arguments read from the path, the query or a JSON body, those left out given their defaults, and its result written in the one JSON shape with the status `status:` gives it. A method's error answers 500, which a caller's command takes as Uncertain; ErrStale and ErrExpired answer a @fresh command's outcomes.", ct.Name, served)}
	sig := "s " + c.service
	if ct.HTTP.AuthSecret != "" {
		paras = append(paras, "", fmt.Sprintf("secret is the secret %s: a request without it in its %s header%s gets 401 and reaches no method. With an empty secret, every request does.", ct.HTTP.AuthSecret, ct.HTTP.AuthHeader, bearerNote(ct)))
		sig += ", secret string"
	}
	g.comment("", paras...)
	g.p("func New%sHandler(%s) http.Handler {", ct.Name, sig)
	g.p("\treturn &server{")
	g.p("\t\tname: %q,", served)
	if ct.HTTP.AuthSecret != "" {
		g.p("\t\tauthHeader: %q,", ct.HTTP.AuthHeader)
		g.p("\t\tsecret: secret,")
		g.p("\t\tbearer: %v,", ct.HTTP.AuthBearer)
	}
	g.p("\t\troutes: []route{")
	for _, o := range c.ops {
		g.p("\t\t\t{op: %q, method: %q, segments: strings.Split(%q, \"/\"), serve: func(r *request) reply {", o.op.Name, o.op.HTTP.Method, o.op.HTTP.Path)
		g.serveOp(c, o)
		g.p("\t\t\t}},")
	}
	g.p("\t\t},")
	g.p("\t}")
	g.p("}")
	g.p("")
}

func contractName(ct *ir.Contract) string {
	if ct.Module.Path == "" {
		return ct.Name
	}
	return ct.Module.Path + "." + ct.Name
}

func (g *goGen) serveOp(c *contract, o *operation) {
	op := o.op
	const in = "\t\t\t\t"
	if o.args != "" {
		g.p(in+"var args %s", o.args)
	}
	for _, pp := range o.params {
		t := resolve(pp.t)
		read := fmt.Sprintf("arg(r, %q, %q, %v, %s)", pp.in, pp.wire, pp.option, g.dec(pp.t))
		if t.Decl == nil && (t.Name == "List" || t.Name == "Set") && len(t.Args) == 1 {
			read = fmt.Sprintf("argList(r, %q, %q, %v, %s)", pp.in, pp.wire, pp.option, g.dec(t.Args[0]))
		}
		field := "args." + goName(pp.p.Name)
		g.p(in + "{")
		g.p(in+"\tv, found, err := %s", read)
		g.p(in + "\tif err != nil {")
		g.p(in+"\t\treturn r.badArg(%q, err)", pp.wire)
		g.p(in + "\t}")
		set := field + " = v"
		if pp.optional && !g.isInterface(pp.t) {
			set = field + " = &v"
		}
		switch {
		case pp.def != nil:
			g.p(in + "\tif !found {")
			g.p(in+"\t\tif v, err = %s(json.RawMessage(%s)); err != nil {", g.dec(pp.t), strconv.Quote(string(pp.def)))
			g.p(in + "\t\t\treturn r.fault(err)")
			g.p(in + "\t\t}")
			g.p(in + "\t}")
			g.p("%s\t%s", in, set)
		case pp.option:
			g.p(in + "\tif found {")
			g.p("%s\t\t%s", in, set)
			g.p(in + "\t}")
		default:
			g.p(in + "\tif !found {")
			g.p(in+"\t\treturn r.missing(%q)", pp.wire)
			g.p(in + "\t}")
			g.p("%s\t%s", in, set)
		}
		g.p(in + "}")
	}
	var call []string
	call = append(call, "r.ctx")
	if o.args != "" {
		call = append(call, "args")
	}
	if op.Key {
		g.p(in+"key, ok := r.key(%q, %q)", wire.KeyHeader(op), op.KeyField)
		g.p(in + "if !ok {")
		g.p(in+"\treturn r.noKey(%q, %q)", wire.KeyHeader(op), op.KeyField)
		g.p(in + "}")
		call = append(call, "key")
	}
	g.p(in+"res, err := s.%s(%s)", goName(op.Name), strings.Join(call, ", "))
	g.p(in + "if err != nil {")
	g.p(in+"\treturn r.failed(err, failure{fresh: %v, stale: %d, expired: %d, httpErr: %v})", op.Fresh, wire.ReplyStatus(op, "Stale"), wire.ReplyStatus(op, "Expired"), o.httpErr)
	g.p(in + "}")
	// the status of the result's variant, when `status:` gives one
	n := g.named(o.result)
	if n != nil && n.single() {
		g.p(in+"return r.answer(%d, res)", wire.ReplyStatus(op, n.variants[0].tag))
		return
	}
	var cases []string
	if n != nil && (n.kind == kUnion || n.kind == kEnum) {
		for _, v := range n.variants {
			if code := wire.ReplyStatus(op, v.tag); code != 200 {
				cases = append(cases, fmt.Sprintf("case %s:\n\tstatus = %d", v.name, code))
			}
		}
	}
	if len(cases) == 0 {
		g.p(in + "return r.answer(200, res)")
		return
	}
	g.p(in + "status := 200")
	if n.kind == kUnion {
		g.p(in + "switch res.(type) {")
	} else {
		g.p(in + "switch res {")
	}
	for _, c := range cases {
		g.p("%s%s", in, c)
	}
	g.p(in + "}")
	g.p(in + "return r.answer(status, res)")
}
