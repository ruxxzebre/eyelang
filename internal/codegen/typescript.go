// TypeScript writes the TypeScript module for one module's contracts: its
// types as the JSON they are on the wire, a variant type as a union
// discriminated on "kind"; a client class for each contract; and a service
// interface with a handler that serves it as a Fetch API function from
// Request to Response.
func TypeScript(prog *ir.Program, mod *ir.Module, opts Options) ([]byte, error) {
	u, err := build(prog, mod)
	if err != nil {
		return nil, err
	}
	g := &tsGen{unit: u}
	g.header(opts.Source)
	for _, n := range u.types {
		g.namedType(n)
	}
	for _, c := range u.contracts {
		g.client(c)
		g.service(c)
	}
	g.b.WriteString(tsHelpers)
	if len(u.errs) > 0 {
		return nil, fmt.Errorf("%s", strings.Join(u.errs, "\n"))
	}
	return g.b.Bytes(), nil
}

// TSCArgs are the tsc flags the generated TypeScript compiles with: strict,
// for ES2022 with the Fetch API's types, as Node 18 and later, Deno, Bun and
// browsers have them.
func TSCArgs(outDir string) []string {
	return []string{"--strict", "--target", "es2022", "--module", "es2022", "--moduleResolution", "bundler", "--lib", "es2022,dom", "--outDir", outDir}
}

// tsReserved are the global names the generated TypeScript uses, which a
// type of the program can't shadow.
var tsReserved = []string{"Array", "Boolean", "Error", "Headers", "JSON", "Number", "Object", "Partial", "Promise", "Record", "Request", "RequestInit", "Required", "Response", "String", "URL", "URLSearchParams"}

func init() {
	for _, name := range tsReserved {
		reserved[name] = true
	}
}

type tsGen struct {
	*unit
	b bytes.Buffer
}

func (g *tsGen) p(format string, args ...any) {
	fmt.Fprintf(&g.b, format, args...)
	g.b.WriteByte('\n')
}

// doc writes a `##` comment as a JSDoc comment, with paragraphs of the
// generator's own prose after it.
func (g *tsGen) doc(indent, doc string, paragraphs ...string) {
	lines := docLines(doc)
	if len(lines) > 0 && len(paragraphs) > 0 {
		lines = append(lines, "")
	}
	lines = append(lines, wrap(paragraphs...)...)
	if len(lines) == 0 {
		return
	}
	for i, l := range lines {
		lines[i] = strings.ReplaceAll(l, "*/", "*\\/")
	}
	if len(lines) == 1 {
		g.p("%s/** %s */", indent, lines[0])
		return
	}
	g.p("%s/**", indent)
	for _, l := range lines {
		if l == "" {
			g.p("%s *", indent)
		} else {
			g.p("%s * %s", indent, l)
		}
	}
	g.p("%s */", indent)
}

func (g *tsGen) header(source string) {
	from := ""
	if source != "" {
		from = " from " + source
	}
	g.p("// Code generated by eye gen ts%s; DO NOT EDIT.", from)
	g.p("//")
	var names []string
	for _, c := range g.contracts {
		names = append(names, c.ct.Name)
	}
	what := "contract " + names[0]
	if len(names) > 1 {
		what = "contracts " + joinWords(names)
	}
	g.p("// The types of %s, a client that calls it over HTTP and a server", what)
	g.p("// stub to implement it, from Eyelang module %s. Values go over the wire in", g.mod.Path)
	g.p("// Eyelang's one JSON shape (SPECS.md §17), which these types describe.")
	g.p("")
	g.p("/* eslint-disable */")
	g.p("")
}

// typ is t's TypeScript type.
func (g *tsGen) typ(t *ir.TypeExpr) string {
	t = resolve(t)
	if inner := g.optionOf(t); inner != nil {
		return g.typ(inner) + " | null"
	}
	if t.Decl != nil {
		if n := g.named(t); n != nil {
			return n.name
		}
		return "unknown"
	}
	switch t.Name {
	case "String", "Key", "Zone", "Instant", "Date", "Time":
		return "string"
	case "Int", "Float", "Duration", "Size":
		return "number"
	case "Bool":
		return "boolean"
	case "Version", "Approval":
		return t.Name
	case "()":
		return "null"
	case "List", "Set":
		if len(t.Args) == 1 {
			elem := g.typ(t.Args[0])
			if strings.Contains(elem, " ") {
				return "Array<" + elem + ">"
			}
			return elem + "[]"
		}
	case "Map":
		if len(t.Args) == 2 {
			k, v := g.typ(t.Args[0]), g.typ(t.Args[1])
			if n := g.named(t.Args[0]); n != nil && n.kind == kEnum {
				return "Partial<Record<" + k + ", " + v + ">>"
			}
			return "Record<" + k + ", " + v + ">"
		}
	}
	return "unknown"
}

// textKind is how an argument written as text, in a path segment or a query
// parameter, is read: "string", "number", "boolean" or "json".
func (g *tsGen) textKind(t *ir.TypeExpr) string {
	t = resolve(t)
	if inner := g.optionOf(t); inner != nil {
		return g.textKind(inner)
	}
	if n := g.named(t); n != nil {
		switch n.kind {
		case kNewtype:
			return g.textKind(n.inner)
		case kEnum:
			return "string"
		}
		return "json"
	}
	switch t.Name {
	case "String", "Key", "Zone", "Instant", "Date", "Time", "Version":
		return "string"
	case "Int", "Float", "Duration", "Size":
		return "number"
	case "Bool":
		return "boolean"
	}
	return "json"
}

func (g *tsGen) namedType(n *named) {
	switch n.kind {
	case kRecord:
		g.doc("", n.doc)
		g.p("export interface %s {", n.name)
		g.fields(n.fields)
		g.p("}")
	case kNewtype:
		g.doc("", n.doc)
		g.p("export type %s = %s;", n.name, g.typ(n.inner))
	case kEnum:
		var values []string
		var docs []string
		for _, v := range n.variants {
			values = append(values, fmt.Sprintf("%q", v.value))
			if v.doc != "" {
				docs = append(docs, fmt.Sprintf("%q: %s", v.value, strings.Join(docLines(v.doc), " ")))
			}
		}
		g.doc("", n.doc, docs...)
		g.p("export type %s = %s;", n.name, strings.Join(values, " | "))
	case kUnion:
		var names []string
		for _, v := range n.variants {
			names = append(names, v.name)
		}
		if !n.single() {
			g.doc("", n.doc)
			g.p("export type %s = %s;", n.name, strings.Join(names, " | "))
		}
		for i, v := range n.variants {
			doc := v.doc
			if n.single() && doc == "" {
				doc = n.doc
			}
			if i > 0 || !n.single() {
				g.p("")
			}
			g.doc("", doc)
			g.p("export interface %s {", v.name)
			g.p("  kind: %q;", v.tag)
			g.fields(v.fields)
			g.p("}")
		}
	}
	g.p("")
}

func (g *tsGen) fields(fields []field) {
	for _, f := range fields {
		g.doc("  ", f.doc)
		if g.optionOf(resolve(f.t)) != nil {
			g.p("  %s?: %s;", f.wire, g.typ(f.t))
		} else {
			g.p("  %s: %s;", f.wire, g.typ(f.t))
		}
	}
}

// results are the types a client's call and a service's method give: a
// command adds Uncertain, a lost reply, on the client's side, and a @fresh
// one Stale and Expired on both.
func (g *tsGen) results(o *operation) (client, service string) {
	r := g.typ(o.result)
	service = r
	if o.op.Fresh {
		service += " | Stale | Expired"
	}
	client = service
	if o.op.Command {
		client += " | Uncertain"
	}
	return client, service
}

func (g *tsGen) params(o *operation, args string) string {
	var in []string
	if o.args != "" {
		in = append(in, "args: "+args)
	}
	if o.op.Key {
		in = append(in, "key: string")
	}
	return strings.Join(in, ", ")
}

func (g *tsGen) auth(ct *ir.Contract) string {
	if ct.HTTP.AuthSecret == "" {
		return "null"
	}
	return fmt.Sprintf("{ header: %q, bearer: %v }", ct.HTTP.AuthHeader, ct.HTTP.AuthBearer)
}

func (g *tsGen) client(c *contract) {
	ct := c.ct
	g.p("// ---------------------------------------------------------------- %s", ct.Name)
	g.p("")
	for _, o := range c.ops {
		if o.args == "" {
			continue
		}
		g.doc("", fmt.Sprintf("The arguments of %s.%s.", ct.Name, o.op.Name))
		g.p("export interface %s {", o.args)
		for _, pp := range o.params {
			switch {
			case pp.def != nil:
				g.doc("  ", fmt.Sprintf("%s when left out.", strings.ReplaceAll(string(pp.def), "\n", " ")))
				g.p("  %s?: %s;", pp.wire, g.typ(pp.t))
			case pp.option:
				g.p("  %s?: %s | null;", pp.wire, g.typ(pp.t))
			default:
				g.p("  %s: %s;", pp.wire, g.typ(pp.t))
			}
		}
		g.p("}")
		g.p("")
	}
	g.doc("", ct.Doc, fmt.Sprintf("%s calls %s's operations over HTTP. A command whose reply was lost gives Uncertain; a request that never reached the service throws the error that stopped it, and can be sent again.", c.client, ct.Name))
	g.p("export class %s {", c.client)
	g.p("  private readonly options: ClientOptions;")
	g.p("")
	if ct.HTTP.AuthSecret != "" {
		g.doc("  ", "", fmt.Sprintf("options.secret is the secret %s, which every request carries in its %s header.", ct.HTTP.AuthSecret, ct.HTTP.AuthHeader))
	}
	g.p("  constructor(options: ClientOptions) {")
	if ct.HTTP.AuthSecret != "" {
		g.p("    if (options.secret === undefined) {")
		g.p("      throw new Error(%q);", fmt.Sprintf("%s needs the secret %s in options.secret", c.client, ct.HTTP.AuthSecret))
		g.p("    }")
	}
	g.p("    this.options = options;")
	g.p("  }")
	for _, o := range c.ops {
		g.p("")
		g.clientOp(c, o)
	}
	g.p("}")
	g.p("")
}

func (g *tsGen) clientOp(c *contract, o *operation) {
	op := o.op
	name := op.Contract.Module.Name + "." + op.Name
	client, _ := g.results(o)
	g.doc("  ", op.Doc, fmt.Sprintf("It is %s %s.", op.HTTP.Method, op.HTTP.Path))
	g.p("  async %s(%s): Promise<%s> {", lowerFirst(op.Name), g.params(o, o.args), client)
	g.p("    const call = newCall(%q, %q, %q);", name, op.HTTP.Method, op.HTTP.Path)
	for _, pp := range o.params {
		v := "args." + pp.wire
		switch {
		case pp.def != nil:
			g.p("    put(call, %q, %q, %s ?? %s);", pp.in, pp.wire, v, string(pp.def))
		case pp.option:
			g.p("    if (%s != null) {", v)
			g.p("      put(call, %q, %q, %s);", pp.in, pp.wire, v)
			g.p("    }")
		default:
			g.p("    put(call, %q, %q, %s);", pp.in, pp.wire, v)
		}
	}
	key := `""`
	if op.Key {
		key = "key"
		g.p("    call.headers[%q] = key;", wire.KeyHeader(op))
		if op.KeyField != "" {
			g.p("    put(call, \"body\", %q, key);", op.KeyField)
		}
	}
	if op.Command {
		g.p("    let reply: Reply;")
		g.p("    try {")
		g.p("      reply = await send(this.options, %s, call);", g.auth(c.ct))
		g.p("    } catch (err) {")
		g.p("      if (notSent(err)) {")
		g.p("        throw err;")
		g.p("      }")
		g.p("      return { kind: \"Uncertain\", key: %s };", key)
		g.p("    }")
	} else {
		g.p("    const reply = await send(this.options, %s, call);", g.auth(c.ct))
	}
	mapped := map[int]bool{}
	if len(o.statuses) > 0 {
		g.p("    switch (reply.status) {")
		var order []string
		cases := map[string][]int{}
		for _, s := range o.statuses {
			mapped[s.code] = true
			if _, ok := cases[s.variant]; !ok {
				order = append(order, s.variant)
			}
			cases[s.variant] = append(cases[s.variant], s.code)
		}
		for _, variant := range order {
			for _, code := range cases[variant] {
				g.p("      case %d:", code)
			}
			g.statusCase(o, variant)
		}
		g.p("    }")
	}
	if op.Fresh {
		if !mapped[wire.StaleStatus] {
			g.p("    if (reply.status === %d) {", wire.StaleStatus)
			g.p("      return { kind: \"Stale\" };")
			g.p("    }")
		}
		if !mapped[wire.ExpiredStatus] {
			g.p("    if (reply.status === %d) {", wire.ExpiredStatus)
			g.p("      return { kind: \"Expired\" };")
			g.p("    }")
		}
	}
	g.p("    if (reply.status >= 200 && reply.status < 300) {")
	if op.Fresh {
		g.p("      const outcome = freshOutcome(reply, %q, %q);", wire.Name("Stale", g.snake), wire.Name("Expired", g.snake))
		g.p("      if (outcome !== null) {")
		g.p("        return outcome;")
		g.p("      }")
	}
	g.p("      return parse(call, reply) as %s;", g.typ(o.result))
	g.p("    }")
	if op.Command && !o.httpErr {
		g.p("    if (reply.status >= 500) {")
		g.p("      return { kind: \"Uncertain\", key: %s };", key)
		g.p("    }")
	}
	g.p("    throw new HttpError(%q, reply.status, reply.text);", name)
	g.p("  }")
}

// statusCase reads a reply whose status `status:` maps to a variant.
func (g *tsGen) statusCase(o *operation, name string) {
	if o.op.Fresh && (name == "Stale" || name == "Expired") {
		g.p("        return { kind: %q };", name)
		return
	}
	n := g.named(o.result)
	var v *variant
	if n != nil {
		for _, x := range n.variants {
			if x.tag == name {
				v = x
			}
		}
	}
	switch {
	case v == nil:
		g.errorf("%s.%s: status: maps a reply to %s, which isn't a variant of %s", o.op.Contract.Name, o.op.Name, name, typeString(o.result))
		g.p("        return undefined as never;")
	case n.kind == kEnum:
		g.p("        return %q;", v.value)
	default:
		g.p("        return { ...fieldsOf(call, reply), kind: %q } as unknown as %s;", v.tag, v.name)
	}
}

func (g *tsGen) service(c *contract) {
	ct := c.ct
	more := []string{fmt.Sprintf("%s is %s's operations that go over HTTP, for a server to implement; %sHandler serves one. Its methods get every argument: those a request leaves out with their defaults, and an Option as null.", c.service, ct.Name, lowerFirst(ct.Name))}
	if s := internalOps(c); s != "" {
		more = append(more, "", s)
	}
	g.doc("", "", more...)
	g.p("export interface %s {", c.service)
	for i, o := range c.ops {
		if i > 0 {
			g.p("")
		}
		_, service := g.results(o)
		g.doc("  ", o.op.Doc)
		g.p("  %s(%s): Promise<%s>;", lowerFirst(o.op.Name), g.params(o, "Required<"+o.args+">"), service)
	}
	g.p("}")
	g.p("")
	served := contractName(ct)
	handler := lowerFirst(ct.Name) + "Handler"
	docs := []string{
		fmt.Sprintf("%s serves a %s over HTTP the way eye run serves %s: each operation at its @http method and path, its arguments read from the path, the query or a JSON body, and its result written in the one JSON shape with the status `status:` gives it. A method that throws answers 500, which a caller's command takes as Uncertain. It checks that the arguments a method needs are there, not their shapes.", handler, c.service, served),
		"",
		"It is a Fetch API handler, from Request to Response, as Deno, Bun and Cloudflare Workers serve one, and Node through an adapter.",
	}
	params := "service: " + c.service
	auth := "null"
	if ct.HTTP.AuthSecret != "" {
		docs = append(docs, "", fmt.Sprintf("secret is the secret %s: a request without it in its %s header%s gets 401 and reaches no method. With an empty secret, every request does.", ct.HTTP.AuthSecret, ct.HTTP.AuthHeader, bearerNote(ct)))
		params += ", secret: string"
		auth = fmt.Sprintf("{ header: %q, bearer: %v, secret }", ct.HTTP.AuthHeader, ct.HTTP.AuthBearer)
	}
	g.doc("", "", docs...)
	g.p("export function %s(%s): (request: Request) => Promise<Response> {", handler, params)
	g.p("  return serve(%q, %s, [", served, auth)
	for _, o := range c.ops {
		g.serveOp(o)
	}
	g.p("  ]);")
	g.p("}")
	g.p("")
}

func (g *tsGen) serveOp(o *operation) {
	op := o.op
	statuses := []string{}
	n := g.named(o.result)
	if n != nil && (n.kind == kUnion || n.kind == kEnum) {
		for _, v := range n.variants {
			if code := wire.ReplyStatus(op, v.tag); code != 200 {
				key := v.tag
				if n.kind == kEnum {
					key = v.value
				}
				statuses = append(statuses, fmt.Sprintf("%q: %d", key, code))
			}
		}
	}
	if op.Fresh {
		for _, name := range []string{"Stale", "Expired"} {
			if code := wire.ReplyStatus(op, name); code != 200 {
				statuses = append(statuses, fmt.Sprintf("%q: %d", name, code))
			}
		}
	}
	g.p("    {")
	g.p("      op: %q,", op.Name)
	g.p("      method: %q,", op.HTTP.Method)
	g.p("      path: %q,", op.HTTP.Path)
	g.p("      httpErr: %v,", o.httpErr)
	if len(statuses) == 0 {
		g.p("      statuses: {},")
	} else {
		g.p("      statuses: { %s },", strings.Join(statuses, ", "))
	}
	if o.args == "" && !op.Key {
		g.p("      serve: async () => {")
	} else {
		g.p("      serve: async (r) => {")
	}
	var call []string
	if o.args != "" {
		g.p("        const args: Required<%s> = {", o.args)
		for _, pp := range o.params {
			t := resolve(pp.t)
			list := t.Decl == nil && (t.Name == "List" || t.Name == "Set") && len(t.Args) == 1
			kind := g.textKind(pp.t)
			if list {
				kind = g.textKind(t.Args[0])
			}
			read := fmt.Sprintf("r.arg(%q, %q, %q, %v, %v)", pp.in, pp.wire, kind, list, pp.option)
			switch {
			case pp.def != nil:
				g.p("          %s: (%s ?? %s) as %s,", pp.wire, read, string(pp.def), g.typ(pp.t))
			case pp.option:
				g.p("          %s: (%s ?? null) as %s | null,", pp.wire, read, g.typ(pp.t))
			default:
				g.p("          %s: r.required(%q, %s) as %s,", pp.wire, pp.wire, read, g.typ(pp.t))
			}
		}
		g.p("        };")
		call = append(call, "args")
	}
	if op.Key {
		g.p("        const key = r.key(%q, %q);", wire.KeyHeader(op), op.KeyField)
		call = append(call, "key")
	}
	g.p("        return await service.%s(%s);", lowerFirst(op.Name), strings.Join(call, ", "))
	g.p("      },")
	g.p("    },")
}
