// Package netpolicy writes the network policy that a program's contracts
// imply (SPECS.md §17): for each contract with @port, the pods of the module
// that serves it accept TCP on that port only from the pods of the modules
// that call it. The output is Kubernetes NetworkPolicy objects
// (networking.k8s.io/v1), and `eye gen policy` prints it.
package netpolicy

import (
	"fmt"
	"io"
	"path/filepath"
	"regexp"
	"slices"
	"strings"

	"eyelang/check"
	"eyelang/ir"
)

// Label is the pod label that names the module a pod runs.
const Label = "eyelang.module"

// Options are what the program doesn't say.
type Options struct {
	// Source is the program's directory as the user named it, for the
	// header comment.
	Source string
	// Namespace is the Kubernetes namespace the policies go in. Empty leaves
	// it out, so `kubectl apply -n` decides.
	Namespace string
}

// Policy is the rule for one contract with @port.
type Policy struct {
	Name     string       // the NetworkPolicy's name
	Contract *ir.Contract // the contract it guards
	Pods     string       // the label value of the pods it selects: the serving module's
	Served   bool         // whether the program serves the contract; if not, Pods is the contract's module
	Port     int
	From     []string // the label values of the modules let in, sorted
}

// Policies returns a rule for each contract with @port in the program,
// sorted by module and contract. The calls the checker refuses get no rule.
func Policies(prog *ir.Program) []Policy {
	program := programName(prog)
	callers := check.Callers(prog)
	var out []Policy
	for _, m := range prog.Modules {
		for _, ct := range m.Contracts {
			if ct.Port == 0 {
				continue // a service outside the network
			}
			p := Policy{Contract: ct, Port: ct.Port, Pods: label(ct.Module, program)}
			for _, s := range servers(ct) {
				p.Pods, p.Served = label(s, program), true
			}
			for _, c := range callers[ct] {
				if from := label(c, program); from != p.Pods && !slices.Contains(p.From, from) {
					p.From = append(p.From, from)
				}
			}
			slices.Sort(p.From)
			p.Name = policyName(program, ct)
			out = append(out, p)
		}
	}
	slices.SortFunc(out, func(a, b Policy) int {
		if c := strings.Compare(a.Contract.Module.Path, b.Contract.Module.Path); c != 0 {
			return c
		}
		return strings.Compare(a.Contract.Name, b.Contract.Name)
	})
	return out
}

// servers returns the modules whose impl serves the contract, sorted: one,
// or none when the program only calls it.
func servers(ct *ir.Contract) []*ir.Module {
	var out []*ir.Module
	for _, op := range ct.Ops {
		if op.Impl != nil && !slices.Contains(out, op.Impl.Module) {
			out = append(out, op.Impl.Module)
		}
	}
	slices.SortFunc(out, func(a, b *ir.Module) int { return strings.Compare(a.Path, b.Path) })
	return out
}

// label is the label value of a module's pods: its import path, or the
// program's name for the program's own module, which @allow can't name.
func label(m *ir.Module, program string) string {
	if m.Path == "" {
		return program
	}
	return m.Path
}

var dnsLabel = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$`)

// Write writes the program's policies as YAML, one document per contract
// with @port, after a header that says where they came from.
func Write(w io.Writer, prog *ir.Program, opts Options) error {
	if opts.Namespace != "" && !dnsLabel.MatchString(opts.Namespace) {
		return fmt.Errorf("the namespace %q isn't a Kubernetes namespace name: up to 63 lower-case letters, digits and '-', starting and ending with a letter or digit", opts.Namespace)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by eye gen policy from %s. Don't edit: change the contracts and generate it again.\n", opts.Source)
	b.WriteString("#\n")
	b.WriteString("# Each contract with @port gets a NetworkPolicy: the pods of the module that\n")
	b.WriteString("# serves it accept TCP on its port only from the pods of the modules that call it.\n")
	fmt.Fprintf(&b, "# A module's pods carry the label %s: <module>.\n", Label)
	policies := Policies(prog)
	if len(policies) == 0 {
		b.WriteString("#\n# The program has no contract with @port, so there is no policy.\n")
	}
	for _, p := range policies {
		writePolicy(&b, p, opts.Namespace)
	}
	_, err := io.WriteString(w, b.String())
	return err
}

func writePolicy(b *strings.Builder, p Policy, namespace string) {
	ct := p.Contract
	b.WriteString("---\n")
	if p.Served {
		fmt.Fprintf(b, "# %s, of module %s, served by module %s on port %d.\n", ct.Name, ct.Module.Path, p.Pods, p.Port)
	} else {
		fmt.Fprintf(b, "# %s, of module %s, on port %d: nothing in the program serves it, so the pods\n", ct.Name, ct.Module.Path, p.Port)
		fmt.Fprintf(b, "# that do are labelled %s: %s.\n", Label, p.Pods)
	}
	switch {
	case len(p.From) > 0:
		fmt.Fprintf(b, "# Let in: %s.\n", andList(p.From))
	case ct.Guarded && len(ct.Allowed) == 0:
		b.WriteString("# Let in: no module of the program, since its @allow is nobody.\n")
	default:
		b.WriteString("# Let in: no module of the program, since none calls it.\n")
	}
	b.WriteString("apiVersion: networking.k8s.io/v1\n")
	b.WriteString("kind: NetworkPolicy\n")
	b.WriteString("metadata:\n")
	fmt.Fprintf(b, "  name: %s\n", p.Name)
	if namespace != "" {
		fmt.Fprintf(b, "  namespace: %s\n", namespace)
	}
	b.WriteString("spec:\n")
	b.WriteString("  podSelector:\n")
	b.WriteString("    matchLabels:\n")
	fmt.Fprintf(b, "      %s: %s\n", Label, p.Pods)
	b.WriteString("  policyTypes:\n")
	b.WriteString("    - Ingress\n")
	if len(p.From) == 0 {
		b.WriteString("  ingress: []\n")
		return
	}
	b.WriteString("  ingress:\n")
	b.WriteString("    - from:\n")
	for _, from := range p.From {
		b.WriteString("        - podSelector:\n")
		b.WriteString("            matchLabels:\n")
		fmt.Fprintf(b, "              %s: %s\n", Label, from)
	}
	b.WriteString("      ports:\n")
	b.WriteString("        - protocol: TCP\n")
	fmt.Fprintf(b, "          port: %d\n", p.Port)
}

// policyName names a contract's policy after the program and the contract,
// such as lab-notify for Notify of module notify in the program testdata/lab,
// so the policies of two programs that call one service add up rather than
// replace each other.
func policyName(program string, ct *ir.Contract) string {
	name := program + "-" + ct.Module.Path
	if !strings.EqualFold(ct.Name, ct.Module.Name) {
		name += "-" + ct.Name
	}
	return dnsName(name)
}

// programName is the name of the program's directory, as a label value.
func programName(prog *ir.Program) string {
	dir := prog.Root.Dir
	if abs, err := filepath.Abs(dir); err == nil {
		dir = abs
	}
	return dnsName(filepath.Base(dir))
}

// dnsName makes s a Kubernetes object name and label value: lower case,
// with '-' for anything but letters and digits.
func dnsName(s string) string {
	var b strings.Builder
	for _, r := range strings.ToLower(s) {
		if r >= 'a' && r <= 'z' || r >= '0' && r <= '9' {
			b.WriteRune(r)
		} else {
			b.WriteByte('-')
		}
	}
	name := strings.Trim(b.String(), "-")
	if len(name) > 63 {
		name = strings.TrimRight(name[:63], "-")
	}
	if name == "" {
		return "program"
	}
	return name
}

func andList(words []string) string {
	if len(words) < 2 {
		return strings.Join(words, "")
	}
	return strings.Join(words[:len(words)-1], ", ") + " and " + words[len(words)-1]
}
